// node behave.mjs <repoRoot>: settings persistence, live sliders, focus handling. Prints PASS/FAIL lines.
import { createRequire } from 'node:module';
import path from 'node:path';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
// pages load from a fake http origin that is served from disk: Chromium won't fetch() from file://
const HOST = 'http://last-call.local';
const ROOT = path.resolve(process.argv[2]);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const ctx = await browser.newContext({ viewport: { width: 960, height: 540 } });
const page = await ctx.newPage();
page.setDefaultTimeout(300000);
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !/ERR_FAILED|fonts\.g/.test(m.text())) errors.push(m.text()); });
await page.route('**/*', (route) => {
  const u = route.request().url();
  if (u.includes('/build/three.module.js')) return route.fulfill({ path: path.join(ROOT, 'tools/vendor/three/build/three.module.js'), contentType: 'text/javascript' });
  if (u.includes('/examples/jsm/')) return route.fulfill({ path: path.join(ROOT, 'tools/vendor/three/examples/jsm', u.split('/examples/jsm/')[1]), contentType: 'text/javascript' });
  if (u.startsWith(HOST)) return route.fulfill({ path: decodeURIComponent(new URL(u).pathname) });
  return route.abort();
});
const url = HOST + path.join(ROOT, 'dist/index.html');
let fails = 0;
const check = (ok, msg) => { console.log(`${ok ? 'PASS' : 'FAIL'} ${msg}`); if (!ok) fails++; };
const active = () => page.evaluate(() => document.activeElement?.id || document.activeElement?.tagName);

await page.goto(url);
await page.waitForSelector('#title-menu:not([hidden])');
check(await active() === 'solo-btn', 'title focuses Play solo');
for (let i = 0; i < 4; i++) await page.keyboard.press('Tab');
check(await active() === 'settings-btn', 'Tab reaches Settings');
await page.keyboard.press('Enter');
const inside = (id) => page.waitForFunction((id) => document.getElementById(id).contains(document.activeElement), id, { timeout: 15000 }).then(() => true, () => false);
check(await inside('settings'), 'opening settings moves focus inside it');
check(await page.evaluate(() => document.getElementById('title').classList.contains('covered')), 'title sheet steps back under settings');
for (let i = 0; i < 20; i++) await page.keyboard.press('Tab');
check(await page.evaluate(() => document.getElementById('settings').contains(document.activeElement)), 'Tab stays trapped in settings after 20 presses');
await page.focus('#vol-music');
await page.keyboard.press('ArrowLeft'); await page.keyboard.press('ArrowLeft');
const music = await page.evaluate(() => ({ v: document.getElementById('vol-music').value, out: document.querySelector('#vol-music + output').textContent, stored: JSON.parse(localStorage.getItem('lastcall.volume')).music }));
check(music.v === '0.4' && music.out === '40%' && music.stored === 0.4, `music slider updates live and stores (${JSON.stringify(music)})`);
await page.click('#speed-seg [data-v="1.5"]');
await page.click('#motion-seg [data-v="on"]');
check(await page.evaluate(() => document.body.classList.contains('reduce-motion')), 'reduce motion toggles the body class');
await page.keyboard.press('Escape');
await page.waitForTimeout(200);
check(await active() === 'settings-btn', 'Escape closes settings and returns focus to its opener');
check(await page.evaluate(() => !document.getElementById('title').classList.contains('covered')), 'title un-covers after closing');
await page.click('#sound-btn');
check(await page.evaluate(() => document.getElementById('sound-btn').getAttribute('aria-pressed') === 'false' && localStorage.getItem('lastcall.muted') === 'true'), 'sound button mutes and persists');
check(await page.evaluate(() => { const r = document.getElementById('sound-btn').getBoundingClientRect(); return document.elementFromPoint(r.x + r.width / 2, r.y + r.height / 2)?.closest('#sound-btn') != null; }), 'sound button is clickable above the title overlay');

await page.reload();
await page.waitForSelector('#title-menu:not([hidden])');
const after = await page.evaluate(() => ({ music: document.getElementById('vol-music').value, out: document.querySelector('#vol-music + output').textContent, speed: document.querySelector('#speed-seg [aria-pressed=true]')?.dataset.v, motion: document.body.classList.contains('reduce-motion'), muted: document.getElementById('sound-btn').getAttribute('aria-pressed') }));
check(after.music === '0.4' && after.out === '40%' && after.speed === '1.5' && after.motion && after.muted === 'false', `settings persist across reload (${JSON.stringify(after)})`);

await page.click('#solo-btn'); await page.click('#solo-start-btn');
await page.waitForFunction(() => document.body.classList.contains('in-game'));
await page.keyboard.press('Escape');
check(await inside('pause') && await active() === 'resume-btn', 'pause focuses Back to the table');
await page.click('#pause-settings-btn');
await inside('settings');
await page.keyboard.press('Escape');
await page.waitForTimeout(150);
check(await active() === 'pause-settings-btn' && await page.evaluate(() => !document.getElementById('pause').classList.contains('covered')), 'closing settings over pause returns focus to the pause menu');
await page.keyboard.press('Escape');
await page.waitForTimeout(150);
check(await page.evaluate(() => document.getElementById('pause').classList.contains('fade')), 'Escape resumes');
check(errors.length === 0, `no page errors (${errors.join(' | ')})`);
await browser.close();
process.exit(fails ? 1 : 0);
